export const variants = effectGroups.flatMap((group, category) => group.variants.map(([name, description], index) => ({
  id: `${group.prefix}${index + 1}`, category, index: index + 1, group: group.id, name, description,
  intensity: approvedEffects[group.id].id === `${group.prefix}${index + 1}` ? approvedEffects[group.id].intensity : 1,
})));

export function spriteUrl(group, color, piece, base = import.meta.env?.BASE_URL ?? '/', material = 'ordinary') {
  if(group==='emperor'&&['w','b'].includes(color))return `${base}pieces/neo/special/${color==='w'?'b-emperor-v2':'b-emperor-final'}.png`;
  if(group==='curse'&&['w','b'].includes(color)&&'pnbrq'.includes(piece)&&piece.length===1&&['ordinary','stone','glass','diamond','ethereal'].includes(material))return `${base}pieces/neo/${material==='ordinary'?'':material+'/'}${color}${piece}.png`;
  if (!['diamond', 'ethereal', 'power'].includes(group) || !['w', 'b'].includes(color) || !'pnbrq'.includes(piece) || piece.length !== 1) throw new Error('Недопустимая фигура для эффекта');
  return `${base}pieces/neo/${group === 'power' ? '' : `${group}/`}${color}${piece}.png`;
}
